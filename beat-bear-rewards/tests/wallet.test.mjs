import assert from 'node:assert/strict';
const stored = new Map();
globalThis.localStorage = { get length() { return stored.size; }, key: i => [...stored.keys()][i] ?? null, getItem: k => stored.get(k) ?? null, setItem: (k, v) => stored.set(k, String(v)), removeItem: k => stored.delete(k) };
globalThis.window = new EventTarget();
const { wallet, addPaws, spendPaws, getDemoSnapshot, replaceDemoSnapshot } = await import('../wallet.mjs');
assert.equal(wallet.paws, 0);
assert.equal(addPaws(-200, 'invalid'), false);
assert.equal(addPaws(1.5, 'invalid'), false);
assert.equal(addPaws(550, 'demo pack'), true);
assert.equal(spendPaws(600, 'overspend'), false);
assert.equal(wallet.paws, 550);
assert.equal(spendPaws(30, 'Ember'), true);
assert.equal(wallet.paws, 520);
assert.equal(addPaws(12, 'completed track', 'earned'), true);
assert.equal(wallet.paws, 532);
assert.equal(wallet.demo, 550);
assert.equal(wallet.earned, 12);
assert.deepEqual(wallet.activity.map(e => e.amount), [12, -30, 550]);
const reloaded = await import('../wallet.mjs?reload');
assert.equal(reloaded.wallet.paws, 532);
assert.equal(reloaded.wallet.activity.length, 3);
localStorage.setItem('beatbear:score:cave:normal', '1234');
localStorage.setItem('unrelated-app-data', 'keep');
const cloud = getDemoSnapshot();
assert.equal(cloud.version, 1);
assert.equal(cloud.scores['beatbear:score:cave:normal'], 1234);
assert.equal(cloud.scores['unrelated-app-data'], undefined);
localStorage.setItem('beatbear:score:fuzz:hard', '888');
replaceDemoSnapshot(cloud);
assert.equal(localStorage.getItem('beatbear:score:cave:normal'), '1234');
assert.equal(localStorage.getItem('beatbear:score:fuzz:hard'), null);
assert.equal(localStorage.getItem('unrelated-app-data'), 'keep');
assert.throws(() => replaceDemoSnapshot({ version: 2 }), /unsupported format/);
stored.set('beatbear:rewards:preview:v1', JSON.stringify({ paws: -5, unlocked: { includes: 3 }, activity: [null, { amount: 2 }] }));
const malformed = await import('../wallet.mjs?malformed');
assert.equal(malformed.wallet.paws, 0);
assert.deepEqual(malformed.wallet.unlocked, ['classic']);
assert.deepEqual(malformed.wallet.activity, []);
const change = new Event('storage');
Object.assign(change, { key: 'beatbear:rewards:preview:v1', newValue: JSON.stringify({ paws: 25, earned: 25, unlocked: ['aurora'] }) });
window.dispatchEvent(change);
assert.equal(malformed.wallet.paws, 25);
assert.deepEqual(malformed.wallet.unlocked, ['classic', 'aurora']);
globalThis.localStorage.setItem = () => { throw Error('Storage blocked'); };
assert.equal(malformed.addPaws(1, 'Session-only'), true);
assert.equal(malformed.wallet.paws, 26);
console.log('PASS: invalid amounts, overspend rejection, earned/demo accounting, activity, reload, cross-tab sync, malformed storage and storage failure.');
