import assert from 'node:assert/strict';
const stored = new Map();
globalThis.localStorage = { getItem: k => stored.get(k) ?? null, setItem: (k, v) => stored.set(k, v) };
globalThis.window = new EventTarget();
const { wallet, addPaws, spendPaws } = await import('../wallet.mjs');
assert.equal(wallet.paws, 0);
assert.equal(addPaws(-200, 'invalid'), false);
assert.equal(addPaws(1.5, 'invalid'), false);
assert.equal(addPaws(550, 'demo pack'), true);
assert.equal(spendPaws(600, 'overspend'), false);
assert.equal(wallet.paws, 550);
assert.equal(spendPaws(30, 'Ember'), true);
assert.equal(wallet.paws, 520);
assert.equal(addPaws(12, 'completed track', 'earned'), true);
assert.equal(wallet.paws, 532);
assert.equal(wallet.demo, 550);
assert.equal(wallet.earned, 12);
assert.deepEqual(wallet.activity.map(e => e.amount), [12, -30, 550]);
const reloaded = await import('../wallet.mjs?reload');
assert.equal(reloaded.wallet.paws, 532);
assert.equal(reloaded.wallet.activity.length, 3);
console.log('PASS: invalid amounts, overspend rejection, earned/demo accounting, activity and reload persistence.');
